# асинхронні подання (async def) у Django не потрібні для більшості типових проєктів.

# але є конкретні сценарії, де async дає реальну перевагу.

# синхронний код блокує потік, поки чекає на щось повільне:
# - запит до зовнішнього API (наприклад, погода, платіжні системи, Google Maps)
# - читання великих файлів або мережеві операції
# - стрімінг відповідей (наприклад, чат, live-дашборд, повільна генерація CSV)

# у синхронному режимі сервер просто "сидить і чекає" — інші запити стоять у черзі.
# у асинхронному режимі (з ASGI-сервером типу Daphne / Uvicorn):

# коли подання робить await (наприклад, await httpx.get(...)), воно віддає контроль назад у event loop.
# сервер може в цей момент обробляти інші запити паралельно (сотні / тисячі з'єднань на одному потоці).
# як результат, буде значно вища пропускна здатність (throughput) при високому навантаженні з I/O.

# реальні приклади:
# - агрегатор цін/готелів/авіаквитків — один запит збирає дані з 5–10 зовнішніх API, і async дозволяє паралельно чекати всі, а не по черзі.
# - чат / реал-тайм дашборд / notifications (WebSockets + Channels).
# - сервіси з довгими стрімінг-відповідями (наприклад, генерація великих звітів на льоту).
# - API, які часто викликають зовнішні сервіси (наприклад, робота з open-meteo на 39 рядку — ідеальний кейс).

# коли async НЕ дає помітної переваги (або стане навіть гірше):
# - більшість запитів — чисто CPU-операції або швидкі ORM-запити (Django ORM все ще синхронний за замовчуванням).
# - низьке навантаження (< 100–200 запитів/сек) — синхронний код часто відпрацьовує швидше.
# - після переходу на async можна не побачити зростання швидкості, бо більшість часу витрачається на синхронний ORM.

################################################################################################################################

# доречі, стандартний сервер python manage.py runserver у Django не є повноцінно асинхронним.
# runserver за замовчуванням працює на WSGI-режимі (синхронному сервері).
# якщо зробити async def подання — Django його запускає його в одноразовому event loop на потоці), тому await asyncio.sleep(...) не повісить весь сервер.
# але справжньої конкурентності (паралельне оброблення кількох запитів під час очікування I/O) немає — бо WSGI-сервер обробляє запити послідовно в одному потоці (або в пулі потоків, але не async).
# в результаті async-подання працюють, але не ефективніше синхронних при високому навантаженні або багатьох одночасних запитах.
# перевага async проявляється тільки під ASGI-сервером.

