from django.http import HttpResponse, JsonResponse
from django.views.decorators.http import require_GET, require_POST # декоратори для обмеження методів запиту
import asyncio
import time
import httpx # .\env\Scripts\activate, pip install httpx

######################################################################
# синхронні подання (звичайні, блокуючі)

def hello_sync(request):
    """Просте синхронне привітання"""
    return HttpResponse("<h1>Привіт! Це синхронне подання 🌤️</h1>")


@require_GET # обмежує цей маршрут лише GET-запитами
def time_sync(request):
    """Повертає поточний час (синхронно)"""
    current_time = time.strftime("%H:%M:%S")
    return HttpResponse(f"<h2>Зараз: {current_time}</h2>")


@require_POST # обмежує цей маршрут лише POST-запитами
def echo_sync(request):
    """Повертає назад те, що прийшов у POST-запиті (синхронно)"""
    message = request.POST.get("message", "нічого не надіслано")
    return JsonResponse({"received": message, "method": "sync"})


######################################################################
# aсинхронні подання (async def + await)

async def hello_async(request):
    """Просте асинхронне привітання"""
    await asyncio.sleep(0.1) # імітація невеликої асинхронної роботи
    return HttpResponse("<h1>Привіт з асинхронного подання!⚡</h1>")


async def fetch_weather_async(request):
    """
    Реальний приклад асинхронного запиту до зовнішнього API.
    Показує перевагу async при роботі з мережею.
    """
    async with httpx.AsyncClient() as client:
        try:
            response = await client.get("https://api.open-meteo.com/v1/forecast?latitude=46.48&longitude=30.73&current_weather=true")
            data = response.json()
            temp = data["current_weather"]["temperature"]
            wind = data["current_weather"]["windspeed"]
            return JsonResponse({
                "city": "Одеса",
                "temperature": temp,
                "wind_speed": wind,
                "fetched_at": time.strftime("%H:%M:%S"),
                "method": "async"
            })
        except Exception as e:
            return JsonResponse({"error": str(e)}, status=500)

